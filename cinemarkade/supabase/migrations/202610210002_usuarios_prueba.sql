-- Primero crear en Authentication las siguientes cuentas con email confirmado:
-- empleado.prueba@cinemarkade.example
-- cliente.prueba@cinemarkade.example
-- menor.prueba@cinemarkade.example
-- Usar en las tres la contraseña de prueba definida en environment.development.ts.
-- Este SQL no crea ni modifica contraseñas de Authentication.

BEGIN;
SET LOCAL TIME ZONE 'America/Argentina/Buenos_Aires';

CREATE TABLE IF NOT EXISTS public.usuario_prueba (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id uuid NOT NULL UNIQUE REFERENCES public.usuario(id),
    etiqueta text NOT NULL CHECK (char_length(trim(etiqueta)) BETWEEN 1 AND 80),
    tipo text NOT NULL CHECK (tipo IN ('empleado', 'cliente', 'cliente_menor')),
    orden integer NOT NULL DEFAULT 0,
    activo boolean NOT NULL DEFAULT true
);

ALTER TABLE public.usuario_prueba ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.usuario_prueba FROM PUBLIC, anon, authenticated;

-- Solo se publican los datos de las cuentas de prueba, nunca sus contraseñas.
-- La comprobación del rol real excluye administradores incluso si se modifica
-- el rol de una de estas cuentas posteriormente.
CREATE OR REPLACE VIEW public.usuario_prueba_disponible WITH (security_barrier = true) AS
SELECT
    prueba.id,
    prueba.etiqueta,
    usuario.mail,
    prueba.tipo,
    prueba.orden,
    prueba.activo
FROM public.usuario_prueba prueba
JOIN public.usuario usuario ON usuario.id = prueba.usuario_id
WHERE prueba.activo
    AND (
        (prueba.tipo = 'empleado' AND usuario.rol::text = 'empleado')
        OR (prueba.tipo IN ('cliente', 'cliente_menor') AND usuario.rol::text = 'cliente')
    );

REVOKE ALL ON public.usuario_prueba_disponible FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.usuario_prueba_disponible TO anon, authenticated;

DO $$
DECLARE
    perfil record;
    usuario_auth_id uuid;
    rol_perfil public.usuario.rol%TYPE;
BEGIN
    FOR perfil IN
        SELECT * FROM (VALUES
            ('empleado.prueba@cinemarkade.example', 'Empleado de prueba', 'Empleado', 'empleado', 1, DATE '1990-01-15'),
            ('cliente.prueba@cinemarkade.example', 'Cliente adulto', 'Cliente', 'cliente', 2, DATE '1995-06-15'),
            ('menor.prueba@cinemarkade.example', 'Cliente menor de edad', 'Menor', 'cliente_menor', 3, (CURRENT_DATE - INTERVAL '15 years')::date)
        ) AS datos(mail, etiqueta, nombre, tipo, orden, fecha_nacimiento)
    LOOP
        usuario_auth_id := NULL;

        SELECT id INTO usuario_auth_id
        FROM auth.users
        WHERE lower(email) = perfil.mail
            AND email_confirmed_at IS NOT NULL;

        IF usuario_auth_id IS NULL THEN
            RAISE EXCEPTION 'Primero creá y confirmá en Authentication la cuenta %.', perfil.mail;
        END IF;

        IF EXISTS (
            SELECT 1 FROM public.usuario
            WHERE id = usuario_auth_id AND rol::text = 'admin'
        ) THEN
            RAISE EXCEPTION 'La cuenta % es administradora y no puede usarse como perfil de prueba.', perfil.mail;
        END IF;

        rol_perfil := CASE WHEN perfil.tipo = 'empleado' THEN 'empleado' ELSE 'cliente' END;

        INSERT INTO public.usuario (
            id, nombre, apellido, mail, fecha_nacimiento, tipo_sangre,
            color_ojos, cantidad_dias_vacaciones, puntos, rol
        ) VALUES (
            usuario_auth_id, perfil.nombre, 'Prueba', perfil.mail, perfil.fecha_nacimiento,
            'O+', 'Marrón', 14, CASE WHEN perfil.tipo = 'empleado' THEN NULL ELSE 15000 END, rol_perfil
        )
        ON CONFLICT (id) DO NOTHING;

        -- No se reemplazan datos ni puntos de un perfil existente al repetir el SQL.
        IF NOT EXISTS (
            SELECT 1 FROM public.usuario
            WHERE id = usuario_auth_id
                AND mail = perfil.mail
                AND rol = rol_perfil
                AND fecha_nacimiento IS NOT NULL
                AND (
                    (perfil.tipo = 'cliente_menor' AND fecha_nacimiento > (CURRENT_DATE - INTERVAL '18 years')::date)
                    OR (perfil.tipo <> 'cliente_menor' AND fecha_nacimiento <= (CURRENT_DATE - INTERVAL '18 years')::date)
                )
        ) THEN
            RAISE EXCEPTION 'El perfil existente de % no coincide con el rol o la edad de prueba esperados.', perfil.mail;
        END IF;

        INSERT INTO public.usuario_prueba (usuario_id, etiqueta, tipo, orden, activo)
        VALUES (usuario_auth_id, perfil.etiqueta, perfil.tipo, perfil.orden, true)
        ON CONFLICT (usuario_id) DO UPDATE SET
            etiqueta = EXCLUDED.etiqueta,
            tipo = EXCLUDED.tipo,
            orden = EXCLUDED.orden,
            activo = true;
    END LOOP;
END;
$$;

COMMIT;
