-- Ejecutar en el SQL Editor de Supabase antes de usar el módulo de reseñas.
BEGIN;

CREATE TABLE IF NOT EXISTS public.resena (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id uuid NOT NULL REFERENCES public.usuario(id),
    pelicula_id bigint NOT NULL REFERENCES public.pelicula(id),
    estrellas integer NOT NULL,
    comentario text NOT NULL,
    fecha timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.resena
    ALTER COLUMN usuario_id SET NOT NULL,
    ALTER COLUMN pelicula_id SET NOT NULL,
    ALTER COLUMN estrellas SET NOT NULL,
    ALTER COLUMN comentario SET NOT NULL,
    ALTER COLUMN fecha SET NOT NULL,
    ALTER COLUMN fecha SET DEFAULT now(),
    ADD CONSTRAINT resena_estrellas_validas CHECK (estrellas BETWEEN 1 AND 5),
    ADD CONSTRAINT resena_comentario_valido CHECK (char_length(trim(comentario)) BETWEEN 1 AND 300);

CREATE UNIQUE INDEX resena_usuario_pelicula_unica ON public.resena(usuario_id, pelicula_id);
CREATE INDEX resena_pelicula_fecha ON public.resena(pelicula_id, fecha DESC);

ALTER TABLE public.resena ENABLE ROW LEVEL SECURITY;

CREATE POLICY resena_lectura ON public.resena FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY resena_crear_propia ON public.resena FOR INSERT TO authenticated
    WITH CHECK (usuario_id = (SELECT auth.uid()));
CREATE POLICY resena_editar_propia ON public.resena FOR UPDATE TO authenticated
    USING (usuario_id = (SELECT auth.uid())) WITH CHECK (usuario_id = (SELECT auth.uid()));
CREATE POLICY resena_eliminar_propia ON public.resena FOR DELETE TO authenticated
    USING (usuario_id = (SELECT auth.uid()));
CREATE POLICY resena_insert_identidad ON public.resena AS RESTRICTIVE FOR INSERT TO authenticated
    WITH CHECK (usuario_id = (SELECT auth.uid()));
CREATE POLICY resena_update_identidad ON public.resena AS RESTRICTIVE FOR UPDATE TO authenticated
    USING (usuario_id = (SELECT auth.uid())) WITH CHECK (usuario_id = (SELECT auth.uid()));
CREATE POLICY resena_delete_identidad ON public.resena AS RESTRICTIVE FOR DELETE TO authenticated
    USING (usuario_id = (SELECT auth.uid()));

REVOKE ALL ON public.resena FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.resena TO anon, authenticated;
GRANT INSERT (usuario_id, pelicula_id, estrellas, comentario) ON public.resena TO authenticated;
GRANT UPDATE (estrellas, comentario) ON public.resena TO authenticated;
GRANT DELETE ON public.resena TO authenticated;

DO $$
DECLARE
    secuencia text := pg_get_serial_sequence('public.resena', 'id');
BEGIN
    IF secuencia IS NOT NULL THEN
        EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO authenticated', secuencia);
    END IF;
END;
$$;

-- Vista pública limitada: muestra el nombre del autor sin exponer su perfil,
-- mail u otros datos personales. Las escrituras siguen protegidas por RLS.
CREATE VIEW public.resena_detalle WITH (security_barrier = true) AS
SELECT
    r.id,
    r.usuario_id,
    r.pelicula_id,
    r.estrellas,
    r.comentario,
    r.fecha,
    u.nombre AS autor_nombre,
    p.nombre AS pelicula_nombre,
    p.imagen AS pelicula_imagen
FROM public.resena r
JOIN public.usuario u ON u.id = r.usuario_id
JOIN public.pelicula p ON p.id = r.pelicula_id;

REVOKE ALL ON public.resena_detalle FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.resena_detalle TO anon, authenticated;

COMMIT;
